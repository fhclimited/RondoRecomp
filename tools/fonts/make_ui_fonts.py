"""Generate tools/frontend/ui_fonts.c: the menus' fonts built into rondo.exe.

All three are under the SIL Open Font License 1.1 (OFL-*.txt beside them), from
https://github.com/google/fonts (ofl/cinzel, ofl/cinzeldecorative, ofl/unifrakturmaguntia):

    Cinzel.ttf                    menu text            Cinzel[wght].ttf, the Cinzel Project Authors
    CinzelDecorative-Bold.ttf     capitals ("CASTLEVANIA")   Natanael Gama
    UnifrakturMaguntia-Book.ttf   titles (blackletter)  j. 'mach' wust, Peter Wiegel

usage: python tools/fonts/make_ui_fonts.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
FONTS = [("th_font_text", "Cinzel.ttf"), ("th_font_caps", "CinzelDecorative-Bold.ttf"),
         ("th_font_title", "UnifrakturMaguntia-Book.ttf")]

out = os.path.join(ROOT, "tools", "frontend", "ui_fonts.c")
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("/* Generated by tools/fonts/make_ui_fonts.py from the fonts in tools/fonts (SIL Open Font\n"
            " * License 1.1: Cinzel, Cinzel Decorative, UnifrakturMaguntia). Do not edit. */\n"
            "#include \"ui_fonts.h\"\n\n")
    for name, file in FONTS:
        data = open(os.path.join(HERE, file), "rb").read()
        f.write(f"/* {file} */\nconst unsigned int {name}_size = {len(data)};\n")
        f.write(f"const unsigned char {name}[{len(data)}] = {{\n")
        for i in range(0, len(data), 24):
            f.write("    " + ",".join(str(b) for b in data[i:i + 24]) + ",\n")
        f.write("};\n\n")
print(out)
