"""Generate runtime/pce/kanji_font.c from the Shinonome (東雲) bitmap fonts.

The System Card's font call (EX_GETFNT) returns 12x12 or 16x16 glyphs for Shift-JIS codes in
JIS rows 0x21-0x27 (symbols, digits, Latin, kana, Greek, Cyrillic) and 0x30-0x4F (level-1
kanji). Players do not supply a System Card, so the glyphs come from Shinonome Gothic, a
public-domain font of the same design sizes:

    http://openlab.jp/efont/dist/shinonome/shinonome-0.9.11p1.tar.bz2
    sha256 95663c95c92ba5765f63ccbdf033eb93b707be01812a989c548db943479c838f
    files bdf/shnmk12.bdf, bdf/shnmk16.bdf (LICENSE: public domain)

usage: python tools/fonts/make_kanji_font.py SHINONOME_BDF_DIR
"""
import os
import sys

ROWS = list(range(0x21, 0x28)) + list(range(0x30, 0x50))   # the System Card's set
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def load_bdf(path, size):
    glyphs, enc, bits = {}, None, None
    for line in open(path, encoding="latin-1"):
        p = line.split()
        if not p:
            continue
        if p[0] == "ENCODING":
            enc = int(p[1])
        elif p[0] == "BBX":
            assert p[1:3] == [str(size), str(size)], line
        elif p[0] == "BITMAP":
            bits = []
        elif p[0] == "ENDCHAR":
            assert len(bits) == size
            glyphs[enc] = bits
            bits = None
        elif bits is not None:
            v = int(p[0], 16)
            bits.append(v >> (len(p[0]) * 4 - size))      # left-aligned in the hex digits
    return glyphs


def pack12(rows):
    """12 rows of 12 bits -> 18 bytes, two rows in three bytes (as the System Card stores them)."""
    out = []
    for i in range(0, 12, 2):
        a, b = rows[i], rows[i + 1]
        out += [a >> 4, ((a & 15) << 4) | (b >> 8), b & 255]
    return out


def pack16(rows):
    out = []
    for r in rows:
        out += [r >> 8, r & 255]
    return out


def emit(f, name, cells, width):
    f.write(f"const uint8_t {name}[KANJI_CELLS][{width}] = {{\n")
    for cell in cells:
        f.write("    {" + ",".join(f"0x{b:02X}" for b in cell) + "},\n")
    f.write("};\n\n")


def main():
    bdf = sys.argv[1]
    k12 = load_bdf(os.path.join(bdf, "shnmk12.bdf"), 12)
    k16 = load_bdf(os.path.join(bdf, "shnmk16.bdf"), 16)
    c12, c16, have = [], [], 0
    for r in ROWS:
        for c in range(0x21, 0x7F):
            code = r << 8 | c
            g12, g16 = k12.get(code), k16.get(code)
            have += g12 is not None
            c12.append(pack12(g12) if g12 else [0] * 18)
            c16.append(pack16(g16) if g16 else [0] * 32)
    out = os.path.join(ROOT, "runtime", "pce", "kanji_font.c")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Generated by tools/fonts/make_kanji_font.py from the Shinonome Gothic bitmap fonts\n"
                " * (shnmk12.bdf, shnmk16.bdf; public domain, The Electronic Font Open Laboratory).\n"
                " * Do not edit. See kanji_font.h. */\n#include \"kanji_font.h\"\n\n")
        emit(f, "kanji_font12", c12, 18)
        emit(f, "kanji_font16", c16, 32)
    print(f"{out}: {len(ROWS)} JIS rows, {have} glyphs")


if __name__ == "__main__":
    main()
